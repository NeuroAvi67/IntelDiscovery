    private fun seedSite(
        userId: String,
        name: String,
        url: String,
        description: String,
        purpose: String,
        categories: List<String>,
        keyFeatures: List<String>,
        accessType: AccessType,
        pricingModel: String,
        freeTierLimitations: String,
        registrationRequired: RegistrationRequirement,
        openSource: Boolean,
        aiPowered: Boolean,
        skillLevel: SkillLevel,
        score: Int,
        label: String,
        why: String,
        advantages: List<String>,
        disadvantages: List<String>,
        who: String
    ): WebsiteResource {
        val domain = extractDomain(url)
        return WebsiteResource(
            id = domainToSlug(domain),
            userId = userId,
            name = name,
            url = url,
            domain = domain,
            description = description,
            purpose = purpose,
            categories = categories,
            keyFeatures = keyFeatures,
            accessType = accessType.wireValue,
            pricingModel = pricingModel,
            freeTierLimitations = freeTierLimitations,
            registrationRequired = registrationRequired.wireValue,
            openSource = openSource,
            aiPowered = aiPowered,
            skillLevel = skillLevel.wireValue,
            recommendationScore = score,
            recommendationLabel = label,
            whyRecommended = why,
            advantages = advantages,
            disadvantages = disadvantages,
            whoShouldUse = who,
            verifiedFacts = "Official primary domain curated in IntelAtlas OSINT directory.",
            sourceType = SourceType.CURATED.wireValue,
            savedByUser = false,
            notes = "",
            tags = categories.map { it.lowercase() }.take(4),
            verificationStatus = VerificationStatus.UNVERIFIED.wireValue,
            httpStatusCode = 0,
            lastCheckedAt = "Pending live probe",
            visitCount = 0
        )
    }
